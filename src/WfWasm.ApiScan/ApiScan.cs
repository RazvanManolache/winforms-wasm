// ApiScan: the parity job, v2 (reflection-based).
// Diffs the public API surface of reference assemblies (the .NET reference
// packs: System.Drawing.Primitives, System.Drawing.Common,
// System.Drawing.Design) against the WfWasm.Drawing implementation assembly
// using ONE shared key builder on both sides, so normalization skew between
// a source parser and reflection cannot produce phantom gaps.
// Reports every missing type or member and exits nonzero while anything is
// missing: the in-suite parity gate runs this same scan and fails until the
// gap is zero, so missing APIs force additions instead of silence.
using System.Reflection;
using System.Text.RegularExpressions;

public static class ApiScan
{
    public static int Main(string[] args)
    {
        if (args.Length < 2 || args.Contains("--help") || args.Contains("-h"))
        {
            Console.Error.WriteLine("usage: WfWasm.ApiScan --ref <asm...> --impl <asm> [--top N] [--only Type]");
            return 2;
        }

        var refAsms = new List<string>();
        string? implAsm = null;
        int top = 50;
        string? only = null;
        bool shapes = false;
        for (int i = 0; i < args.Length; i++)
        {
            if (args[i] == "--ref" || args[i] == "--refasm")
            {
                while (i + 1 < args.Length && !args[i + 1].StartsWith("--", StringComparison.Ordinal))
                    refAsms.Add(args[++i]);
            }
            else if ((args[i] == "--impl" || args[i] == "--implasm") && i + 1 < args.Length)
                implAsm = args[++i];
            else if (args[i] == "--top" && i + 1 < args.Length)
                top = int.Parse(args[++i]);
            else if (args[i] == "--only" && i + 1 < args.Length)
                only = args[++i];
            else if (args[i] == "--shapes")
                shapes = true;
            else
            {
                Console.Error.WriteLine($"unknown arg: {args[i]}");
                return 2;
            }
        }

        if (refAsms.Count == 0 || implAsm is null)
        {
            Console.Error.WriteLine("need --ref <asm...> and --impl <asm>");
            return 2;
        }

        var reference = new ApiSet();
        foreach (string asm in refAsms)
            reference.AddAssembly(asm);
        var implementation = new ApiSet();
        implementation.AddAssembly(implAsm);

        if (only is not null && only == "@aliases")
        {
            Console.WriteLine("// <auto-generated> extern-alias bindings for WfWasm.Drawing. Do not hand-edit.");
            Console.WriteLine("extern alias WfDraw;");
            var emitted = new HashSet<string>();
            foreach (string type in implementation.Types.OrderBy(t => t))
            {
                string cli = type.Replace('+', '.');
                if (cli.Contains('<') || cli.Contains('>'))
                    continue;
                string shortName = cli.Split('.').Last();
                if (!emitted.Add(shortName))
                {
                    Console.Error.WriteLine($"// COLLISION skipped: {cli}");
                    continue;
                }

                Console.WriteLine($"global using {shortName} = WfDraw::{cli};");
            }

            return 0;
        }

        if (only is not null)
        {
            if (reference.Members.TryGetValue(only, out var set))
            {
                Console.WriteLine($"{only}: {set.Count} members");
                foreach (string m in set.OrderBy(x => x))
                    Console.WriteLine($"  {m}");
                Console.WriteLine(implementation.Types.Contains(only)
                    ? "implemented: yes (type present)"
                    : "implemented: NO (type missing)");
            }
            else
            {
                Console.WriteLine($"type {only} not found");
            }

            return 0;
        }

        if (shapes)
            return ShapeCheck(reference, implementation);

        var (missingTypes, missingMembers, missingLines) = Diff(reference, implementation, top);
        int totalMembers = reference.Members.Values.Sum(s => s.Count);
        double parity = (reference.Types.Count + totalMembers) == 0 ? 100.0
            : 100.0 * (reference.Types.Count + totalMembers - missingTypes - missingMembers)
            / (reference.Types.Count + totalMembers);
        Console.WriteLine($"types: {reference.Types.Count} ref, missing types: {missingTypes}");
        Console.WriteLine($"members: {totalMembers} ref, missing: {missingMembers}, parity: {parity:F2}%");
        foreach (string line in missingLines)
            Console.WriteLine(line);
        if (missingLines.Count < missingTypes + missingMembers)
            Console.WriteLine($"... and {missingTypes + missingMembers - missingLines.Count} more (see --top).");
        return missingTypes + missingMembers > 0 ? 1 : 0;
    }

    public static (int MissingTypes, int MissingMembers, List<string> Lines) Diff(
        ApiSet reference, ApiSet implementation, int top)
    {
        int missingTypes = 0;
        int missingMembers = 0;
        var missingLines = new List<string>();
        foreach (string type in reference.Types.OrderBy(t => t))
        {
            if (!implementation.Types.Contains(type))
            {
                missingTypes++;
                // Members of a missing type are missing too: parity is
                // measured over the whole reference surface.
                missingMembers += reference.Members[type].Count;
                if (missingLines.Count < top)
                    missingLines.Add($"TYPE {type}");
                continue;
            }

            foreach (string member in reference.Members[type].OrderBy(m => m))
            {
                if (!implementation.Members[type].Contains(member))
                {
                    missingMembers++;
                    if (missingLines.Count < top)
                        missingLines.Add($"  {type} :: {member}");
                }
            }
        }

        return (missingTypes, missingMembers, missingLines);
    }

    // Field-vs-property (and static/instance, read/write) shape check:
    // the signature gate collapses them, but IL-level fidelity needs them
    // to match. Reports mismatches; nonzero exit while any differ.
    public static int ShapeCheck(ApiSet reference, ApiSet implementation)
    {
        int bad = 0;
        foreach (string type in reference.Types.OrderBy(t => t))
        {
            if (!implementation.ByName.TryGetValue(type, out Type? impl))
                continue;
            Type reft = reference.ByName[type];
            foreach (var (name, rshape) in ShapesOf(reft))
            {
                if (!ShapesOf(impl).TryGetValue(name, out string? ishape))
                    continue;
                if (rshape != ishape)
                {
                    Console.WriteLine($"SHAPE {type}.{name}: ref={rshape} impl={ishape}");
                    bad++;
                }
            }
        }

        Console.WriteLine(bad == 0 ? "shapes: all match" : $"shapes: {bad} mismatches");
        return bad > 0 ? 1 : 0;
    }

    static Dictionary<string, string> ShapesOf(Type type)
    {
        const BindingFlags Flags = BindingFlags.Public | BindingFlags.NonPublic
            | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;
        var map = new Dictionary<string, string>();
        foreach (FieldInfo f in type.GetFields(Flags))
        {
            if (!ApiSet.IsVisible(f) || f.Name.Contains('<'))
                continue;
            map[f.Name] = "field:" + (f.IsStatic ? "s" : "i");
        }

        foreach (PropertyInfo p in type.GetProperties(Flags))
        {
            if (p.GetIndexParameters().Length > 0 || p.Name.Contains('<'))
                continue;
            MethodInfo? access = p.GetMethod ?? p.SetMethod;
            if (access is null || !ApiSet.IsVisible(access))
                continue;
            map[p.Name] = "prop:" + ((p.GetMethod ?? p.SetMethod!)!.IsStatic ? "s" : "i")
                + ":" + (p.CanRead ? "r" : "") + (p.CanWrite ? "w" : "");
        }

        return map;
    }

    public sealed class ApiSet
    {
        public HashSet<string> Types { get; } = new();
        public Dictionary<string, HashSet<string>> Members { get; } = new();
        public Dictionary<string, Type> ByName { get; } = new();

        public void AddAssembly(string path)
        {
            Assembly asm = Assembly.LoadFrom(Path.GetFullPath(path));
            foreach (Type type in asm.GetExportedTypes())
                AddType(type);
        }

        void AddType(Type type)
        {
            if (!IsVisible(type))
                return;
            string full = TypeKey(type);
            Types.Add(full);
            ByName[full] = type;
            HashSet<string> members = GetMembers(full);

            if (type.IsEnum)
            {
                foreach (FieldInfo field in type.GetFields(
                    BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly))
                {
                    if (!field.IsLiteral || field.Name.Contains('<'))
                        continue;
                    members.Add("E:" + field.Name);
                }

                return;
            }

            const BindingFlags Flags = BindingFlags.Public | BindingFlags.NonPublic
                | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;
            foreach (MethodInfo method in type.GetMethods(Flags))
            {
                // Operators carry SpecialName too: only they survive the
                // special-name filter (accessors never appear in source shape).
                bool isOperator = method.Name.StartsWith("op_", StringComparison.Ordinal);
                if (!IsVisible(method) || (method.IsSpecialName && !isOperator))
                    continue;
                if (method.Name.Contains('<') || method.Name.Contains('>'))
                    continue;
                string? key = MethodKey(method);
                if (key is not null)
                    members.Add(key);
            }

            foreach (ConstructorInfo ctor in type.GetConstructors(Flags))
            {
                if (!IsVisible(ctor))
                    continue;
                members.Add($"M:.ctor({ParamKey(ctor.GetParameters())}){(ctor.IsStatic ? "s" : "")}");
            }

            foreach (FieldInfo field in type.GetFields(Flags))
            {
                if (!IsVisible(field) || field.Name.Contains('<'))
                    continue;
                members.Add($"A:{Pretty(field.FieldType)} {field.Name}{(field.IsStatic ? "s" : "")}");
            }

            foreach (PropertyInfo prop in type.GetProperties(Flags))
            {
                if (prop.GetIndexParameters().Length > 0 || prop.Name.Contains('<'))
                    continue;
                MethodInfo? access = prop.GetMethod ?? prop.SetMethod;
                if (access is null || !IsVisible(access))
                    continue;
                bool isStatic = (prop.GetMethod ?? prop.SetMethod!)!.IsStatic;
                members.Add($"A:{Pretty(prop.PropertyType)} {prop.Name}{(isStatic ? "s" : "")}");
            }

            foreach (EventInfo ev in type.GetEvents(Flags))
            {
                MethodInfo? access = ev.AddMethod ?? ev.RemoveMethod;
                if (access is null || !IsVisible(access))
                    continue;
                members.Add($"V:{Pretty(ev.EventHandlerType!)} {ev.Name}");
            }
        }

        HashSet<string> GetMembers(string full)
        {
            if (!Members.TryGetValue(full, out var set))
            {
                set = new HashSet<string>();
                Members[full] = set;
            }

            return set;
        }

        static string TypeKey(Type type)
        {
            var parts = new Stack<string>();
            for (Type? t = type; t is not null; t = t.DeclaringType)
                parts.Push(StripArity(t.Name));
            return (type.Namespace + "." + string.Join("+", parts)).TrimStart('.');
        }

        static string StripArity(string name)
        {
            int tick = name.IndexOf('`');
            return tick >= 0 ? name[..tick] : name;
        }

        static string? MethodKey(MethodInfo method)
        {
            string name = method.Name;
            if (name is "op_Explicit" or "op_Implicit")
            {
                string kind = name == "op_Explicit" ? "explicit" : "implicit";
                return $"O:{kind}({ParamKey(method.GetParameters())})";
            }

            if (name.StartsWith("op_", StringComparison.Ordinal))
            {
                if (!OperatorSymbols.TryGetValue(name, out string? symbol))
                    return null;
                return $"O:operator {symbol}({ParamKey(method.GetParameters())})";
            }

            return $"M:{Pretty(method.ReturnType)} {name}({ParamKey(method.GetParameters())}){(method.IsStatic ? "s" : "")}";
        }

        static readonly Dictionary<string, string> OperatorSymbols = new()
        {
            ["op_Addition"] = "+", ["op_Subtraction"] = "-", ["op_Multiply"] = "*",
            ["op_Division"] = "/", ["op_Modulus"] = "%", ["op_BitwiseAnd"] = "&",
            ["op_BitwiseOr"] = "|", ["op_ExclusiveOr"] = "^", ["op_LeftShift"] = "<<",
            ["op_RightShift"] = ">>", ["op_UnsignedRightShift"] = ">>>",
            ["op_Equality"] = "==", ["op_Inequality"] = "!=", ["op_LessThan"] = "<",
            ["op_GreaterThan"] = ">", ["op_LessThanOrEqual"] = "<=",
            ["op_GreaterThanOrEqual"] = ">=", ["op_UnaryNegation"] = "-",
            ["op_UnaryPlus"] = "+", ["op_LogicalNot"] = "!", ["op_OnesComplement"] = "~",
            ["op_Increment"] = "++", ["op_Decrement"] = "--",
            ["op_True"] = "true", ["op_False"] = "false",
        };

        static string ParamKey(ParameterInfo[] pars)
        {
            var kinds = new List<string>();
            foreach (ParameterInfo p in pars)
            {
                Type t = p.ParameterType;
                string prefix = "";
                if (t.IsByRef)
                {
                    t = t.GetElementType()!;
                    prefix = p.IsOut && !p.IsIn ? "out "
                        : p.IsIn && !p.IsOut ? "in " : "ref ";
                }

                kinds.Add(prefix + Pretty(t));
            }

            return string.Join(",", kinds);
        }

        static readonly Dictionary<string, string> KeywordTypes = new()
        {
            ["Boolean"] = "bool", ["Byte"] = "byte", ["SByte"] = "sbyte",
            ["Char"] = "char", ["Decimal"] = "decimal", ["Double"] = "double",
            ["Single"] = "float", ["Int32"] = "int", ["UInt32"] = "uint",
            ["Int64"] = "long", ["UInt64"] = "ulong", ["Int16"] = "short",
            ["UInt16"] = "ushort", ["Object"] = "object", ["String"] = "string",
            ["Void"] = "void", ["IntPtr"] = "nint", ["UIntPtr"] = "nuint",
        };

        public static string Pretty(Type type)
        {
            if (type.IsByRef)
                type = type.GetElementType()!;
            if (type.IsPointer)
                return Pretty(type.GetElementType()!) + "*";
            if (type.IsArray)
                return Pretty(type.GetElementType()!) + "[" + new string(',', type.GetArrayRank() - 1) + "]";
            if (type.IsGenericParameter)
                return type.Name;
            if (type.IsGenericType)
            {
                if (type.GetGenericTypeDefinition() == typeof(Nullable<>))
                    return Pretty(type.GetGenericArguments()[0]) + "?";
                string args = string.Join(",", type.GetGenericArguments().Select(Pretty));
                string def = TypeKey(type.GetGenericTypeDefinition());
                return ShortName(def) + "<" + args + ">";
            }

            if (type.DeclaringType is not null)
                return Pretty(type.DeclaringType) + "+" + StripArity(type.Name);
            if (type.Namespace == "System" && KeywordTypes.TryGetValue(type.Name, out string? keyword))
                return keyword;
            return string.IsNullOrEmpty(type.Namespace) || type.Namespace == "System"
                ? StripArity(type.Name)
                : type.Namespace + "." + StripArity(type.Name);
        }

        static string ShortName(string full)
        {
            // "System.Collections.Generic.List" -> "List"; nested "A+B" keeps tail.
            return full.Split('.').Last();
        }

        internal static bool IsVisible(Type type)
        {
            if (type.IsVisible)
                return true;
            return type.IsNestedPublic || type.IsNestedFamily || type.IsNestedFamORAssem;
        }

        internal static bool IsVisible(MethodBase method) =>
            method.IsPublic || method.IsFamily || method.IsFamilyOrAssembly;

        internal static bool IsVisible(FieldInfo field) =>
            field.IsPublic || field.IsFamily || field.IsFamilyOrAssembly;
    }
}
